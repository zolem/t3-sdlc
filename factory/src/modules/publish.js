// @ts-check
// Turns an approved run into stacks of draft PRs: one stack per repo, each PR
// based on the previous slice in that repo, plus the docs PR on top of the
// primary repo. Multi-repo stacks are cross-linked once every PR exists.
// Refuses to run before the PR-stack gate is approved.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { git } from '../lib/git.js';
import { ledger, loadRun, mutateRun, readRunFile, runFileExists, writeRunFile } from '../lib/runs.js';
import { now } from '../lib/store.js';
import { slicesIn } from '../lib/workspace.js';

/** @param {string} root */
function githubRepo(root) {
  const url = git(root, ['remote', 'get-url', 'origin'], { allowFail: true });
  const m = url && url.match(/github\.com[:/]([^/]+\/[^/.]+?)(?:\.git)?$/);
  return m ? m[1] : null;
}

/** @param {string[]} args @param {string} cwd */
function gh(args, cwd) {
  return execFileSync('gh', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 60_000 }).trim();
}

/**
 * Stacks to publish, one per repo with slices.
 * @param {any} run @param {string} home
 */
function stacks(run, home) {
  const doc = runFileExists(home, run.id, 'slices.json') ? JSON.parse(readRunFile(home, run.id, 'slices.json')) : { slices: [] };
  const out = [];
  for (const r of Object.values(run.repos)) {
    const repo = /** @type {any} */ (r);
    const items = slicesIn(run, repo.name).map((/** @type {any} */ s) => ({ n: s.n, branch: s.branch, title: s.title, spec: doc.slices.find((/** @type {any} */ x) => x.n === s.n) || {}, s }));
    if (run.docs?.headSha && run.docs.repo === repo.name) items.push({ n: run.slices.length + 1, branch: run.docs.branch, title: 'Feature documentation', spec: { summary: `Versioned feature doc at ${run.docs.docPath}`, why: 'Records what changed and why, with diagrams and screenshots.' }, s: null });
    if (items.length) out.push({ repo, gh: githubRepo(repo.root), items });
  }
  return out;
}

/**
 * @param {any} run @param {any} stack @param {number} i @param {string} home @param {{ repo: string, title: string, url: string | null }[]} others
 */
function prBody(run, stack, i, home, others) {
  const it = stack.items[i];
  const multi = Object.keys(run.repos).length > 1;
  const lines = [
    `**${multi ? `${stack.repo.name} ` : ''}stack ${i + 1}/${stack.items.length}** for _${run.title}_${run.intake?.ticket ? ` (${run.intake.ticket})` : ''}`,
    '',
    it.spec.summary || '',
    '',
    `**Why this comes here:** ${it.spec.why || ''}`,
    '',
    '### Stack',
    ...stack.items.map((/** @type {any} */ x, /** @type {number} */ j) => `${j === i ? '➡️' : '  '} ${j + 1}. ${x.title}`),
  ];
  if (multi && others.length) lines.push('', '### Same feature in other repos', ...others.map(o => `- ${o.repo}: ${o.url ? `[${o.title}](${o.url})` : o.title}`));
  if (it.s?.headSha && runFileExists(home, run.id, `checks/${it.s.headSha}.json`)) {
    const c = JSON.parse(readRunFile(home, run.id, `checks/${it.s.headSha}.json`));
    lines.push('', '### Deterministic checks', '| Check | Result |', '|---|---|', ...c.checks.map((/** @type {any} */ x) => `| ${x.id} | ${x.ok ? '✅' : '❌'} ${String(x.summary).split('\n')[0]} |`));
  }
  if (it.s?.lastVerify) {
    lines.push('', '### Review', `Built by \`${it.s.author?.model || 'unknown'}\`; reviewed by a different model family. Round ${it.s.lastVerify.round}: ${it.s.lastVerify.blocking} blocking, ${it.s.lastVerify.minor} minor.`);
  }
  const docsRepo = run.docs?.repo ? run.repos[run.docs.repo] : null;
  const docsGh = docsRepo ? githubRepo(docsRepo.root) : null;
  if (docsGh && run.docs?.headSha && run.docs.docPath) {
    const dir = path.posix.join(path.posix.dirname(run.docs.docPath), path.posix.basename(run.docs.docPath, '.md'));
    const pngs = (git(docsRepo.root, ['ls-tree', '-r', '--name-only', run.docs.branch, '--', dir], { allowFail: true }) || '').split('\n').filter(f => /\.(png|jpe?g|gif|webp)$/i.test(f));
    const mine = it.s ? pngs.filter(f => path.basename(f).startsWith(`slice-${it.s.n}-`)) : pngs;
    if (mine.length) lines.push('', '### Screenshots', ...mine.map(f => `![${path.basename(f)}](https://github.com/${docsGh}/blob/${run.docs.branch}/${f}?raw=true)`));
  }
  lines.push('', `<sub>Generated by orchestrate-sdlc run \`${run.id}\`.</sub>`);
  return lines.join('\n');
}

/** @param {string} root @param {string} branch @param {string} base @param {string} title @param {string} body */
function upsertPr(root, branch, base, title, body) {
  const bodyFile = path.join(os.tmpdir(), `orch-pr-${process.pid}-${branch.replace(/\W+/g, '-')}.md`);
  fs.writeFileSync(bodyFile, body);
  try {
    let url;
    try {
      url = gh(['pr', 'view', branch, '--json', 'url', '--jq', '.url'], root);
      gh(['pr', 'edit', branch, '--base', base, '--title', title, '--body-file', bodyFile], root);
    } catch {
      url = gh(['pr', 'create', '--draft', '--head', branch, '--base', base, '--title', title, '--body-file', bodyFile], root).split('\n').pop();
    }
    return url;
  } finally {
    fs.rmSync(bodyFile, { force: true });
  }
}

/** @type {import('../registry.js').ModuleDef} */
export default {
  name: 'publish',
  description: 'Push the approved slice branches and open them as stacks of draft PRs (one stack per repo).',
  functions: {
    stack: {
      signature: 'factory.publish.stack({ runId: string, dryRun?: boolean }): Promise<{ dryRun: boolean, prs: { repo, n, title, branch, base, url }[] }>',
      description: 'Only after the human approved the PR-stack gate. Pushes each branch and creates or updates a draft PR based on the previous slice in the same repo. Repos without a GitHub origin (or runs where publishing was skipped) get a dry-run plan in publish/stack.md instead.',
      tags: ['pr', 'pull request', 'github', 'push', 'stack'],
      handler: ({ runId, dryRun }, ctx) => {
        const run = loadRun(ctx.home, runId);
        if (run.cursor !== 'publish') throw new Error(`Run is at "${run.cursor}". Publishing requires an approved PR-stack gate.`);
        const all = stacks(run, ctx.home);
        const forceDry = Boolean(dryRun) || run.capabilities?.publish === false;
        /** @type {any[]} */
        const prs = [];
        const plan = [`# Publish plan for ${run.id}`, ''];
        const titleOf = (/** @type {any} */ st, /** @type {number} */ i) => `[${Object.keys(run.repos).length > 1 ? `${st.repo.name} ` : ''}${i + 1}/${st.items.length}] ${st.items[i].title}`;
        for (const st of all) {
          const dry = forceDry || !st.gh;
          plan.push(`## ${st.repo.name}${dry ? ` (dry run${st.gh ? '' : ': no GitHub origin remote'})` : ` → ${st.gh}`}`, '');
          st.items.forEach((/** @type {any} */ it, /** @type {number} */ i) => {
            const base = i === 0 ? st.repo.baseBranch : st.items[i - 1].branch;
            const title = titleOf(st, i);
            plan.push(`### ${title}`, '', `\`git push -u origin ${it.branch}\` → draft PR into \`${base}\``, '');
            if (dry) {
              prs.push({ repo: st.repo.name, n: it.n, title, branch: it.branch, base, url: null, dryRun: true });
              return;
            }
            git(st.repo.root, ['push', '-u', 'origin', `${it.branch}:${it.branch}`, '--force-with-lease']);
            const url = upsertPr(st.repo.root, it.branch, base, title, prBody(run, st, i, ctx.home, []));
            prs.push({ repo: st.repo.name, n: it.n, title, branch: it.branch, base, url });
          });
        }
        // Second pass: cross-link stacks across repos now that every PR has a URL.
        if (all.length > 1) {
          for (const st of all) {
            const others = prs.filter(p => p.repo !== st.repo.name).map(p => ({ repo: p.repo, title: p.title, url: p.url }));
            st.items.forEach((/** @type {any} */ it, /** @type {number} */ i) => {
              const pr = prs.find(p => p.branch === it.branch && p.repo === st.repo.name);
              const body = prBody(run, st, i, ctx.home, others);
              if (pr?.url) upsertPr(st.repo.root, it.branch, pr.base, pr.title, body);
            });
          }
        }
        for (const st of all) st.items.forEach((/** @type {any} */ _it, /** @type {number} */ i) => plan.push(`<details><summary>${titleOf(st, i)} body</summary>\n\n${prBody(run, st, i, ctx.home, prs.filter(p => p.repo !== st.repo.name))}\n\n</details>`, ''));
        writeRunFile(ctx.home, runId, 'publish/stack.md', plan.join('\n'));
        mutateRun(ctx.home, runId, r => {
          r.prs = prs;
          r.publishedAt = now();
          r.cursor = 'done';
          r.status = 'done';
        });
        ledger(ctx.home, runId, { event: 'publish.stack', dryRun: prs.every(p => p.dryRun), prs: prs.map(p => p.url) });
        const anyReal = prs.some(p => p.url);
        return { dryRun: !anyReal, prs, plan: 'publish/stack.md', next: anyReal ? 'Call link_pull_request for every url, then factory.orchestrator.next.' : 'Nothing was pushed. Tell the user where the plan is, then call factory.orchestrator.next.' };
      },
    },
  },
};
